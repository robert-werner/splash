import argparse
import struct
import sys
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

# GGUF v3 constants
GGUF_MAGIC = 0x46554747  # "GGUF" in little-endian
GGUF_VERSION = 3
GGUF_DEFAULT_ALIGNMENT = 32

# GGML type constants
GGML_TYPE_Q4_K = 12
GGML_TYPE_PQ2_0 = 142

class GGUFMetadataValue:
    """GGUF metadata value with type"""
    def __init__(self, value_type: int, value):
        self.value_type = value_type
        self.value = value

class GGUFTensor:
    """GGUF tensor descriptor"""
    def __init__(self, name: str, dims: List[int], tensor_type: int, offset: int):
        self.name = name
        self.dims = dims
        self.tensor_type = tensor_type
        self.offset = offset
        self.size = self._calculate_size()
    
    def _calculate_size(self) -> int:
        """Calculate tensor data size in bytes"""
        # Block sizes for different quantization formats
        block_sizes = {
            GGML_TYPE_Q4_K: (256, 144),   # 256 elements per block, 144 bytes per block
            GGML_TYPE_PQ2_0: (128, 34),   # 128 elements per block, 34 bytes per block
        }
        
        if self.tensor_type not in block_sizes:
            raise ValueError(f"Unsupported tensor type: {self.tensor_type}")
        
        elements = 1
        for dim in self.dims:
            elements *= dim
        
        block_elements, block_bytes = block_sizes[self.tensor_type]
        num_blocks = (elements + block_elements - 1) // block_elements
        return num_blocks * block_bytes

class GGUFFile:
    """GGUF file reader/writer"""
    def __init__(self, path: Path):
        self.path = path
        self.metadata: Dict[str, GGUFMetadataValue] = {}
        self.tensors: Dict[str, GGUFTensor] = {}
        self.tensor_data_offset = 0
        self._read_header()
    
    def _read_header(self):
        """Read GGUF header and metadata"""
        with open(self.path, 'rb') as f:
            # Read magic and version
            magic = struct.unpack('<I', f.read(4))[0]
            if magic != GGUF_MAGIC:
                raise ValueError(f"Invalid GGUF magic: {hex(magic)}")
            
            version = struct.unpack('<I', f.read(4))[0]
            if version != GGUF_VERSION:
                raise ValueError(f"Unsupported GGUF version: {version}")
            
            # Read tensor count and metadata count
            tensor_count = struct.unpack('<Q', f.read(8))[0]
            metadata_count = struct.unpack('<Q', f.read(8))[0]
            
            # Read metadata
            for _ in range(metadata_count):
                self._read_metadata_kv(f)
            
            # Read tensor info
            for _ in range(tensor_count):
                self._read_tensor_info(f)
            
            # Calculate tensor data offset (aligned)
            self.tensor_data_offset = (f.tell() + GGUF_DEFAULT_ALIGNMENT - 1) & ~(GGUF_DEFAULT_ALIGNMENT - 1)
    
    def _read_string(self, f) -> str:
        """Read length-prefixed string"""
        length = struct.unpack('<Q', f.read(8))[0]
        return f.read(length).decode('utf-8')
    
    def _read_metadata_kv(self, f):
        """Read metadata key-value pair"""
        key = self._read_string(f)
        value_type = struct.unpack('<I', f.read(4))[0]
        
        # Read value based on type
        if value_type == 0:  # UINT8
            value = struct.unpack('<B', f.read(1))[0]
        elif value_type == 1:  # INT8
            value = struct.unpack('<b', f.read(1))[0]
        elif value_type == 2:  # UINT16
            value = struct.unpack('<H', f.read(2))[0]
        elif value_type == 3:  # INT16
            value = struct.unpack('<h', f.read(2))[0]
        elif value_type == 4:  # UINT32
            value = struct.unpack('<I', f.read(4))[0]
        elif value_type == 5:  # INT32
            value = struct.unpack('<i', f.read(4))[0]
        elif value_type == 6:  # FLOAT32
            value = struct.unpack('<f', f.read(4))[0]
        elif value_type == 7:  # BOOL
            value = struct.unpack('<?', f.read(1))[0]
        elif value_type == 8:  # STRING
            value = self._read_string(f)
        elif value_type == 9:  # ARRAY
            # Skip arrays for now (complex structure)
            array_type = struct.unpack('<I', f.read(4))[0]
            array_len = struct.unpack('<Q', f.read(8))[0]
            # Read and discard array elements
            element_sizes = {0: 1, 1: 1, 2: 2, 3: 2, 4: 4, 5: 4, 6: 4, 7: 1}
            if array_type in element_sizes:
                f.read(array_len * element_sizes[array_type])
            elif array_type == 8:  # String array
                for _ in range(array_len):
                    self._read_string(f)
            value = None
        elif value_type == 10:  # UINT64
            value = struct.unpack('<Q', f.read(8))[0]
        elif value_type == 11:  # INT64
            value = struct.unpack('<q', f.read(8))[0]
        elif value_type == 12:  # FLOAT64
            value = struct.unpack('<d', f.read(8))[0]
        else:
            raise ValueError(f"Unknown metadata type: {value_type}")
        
        self.metadata[key] = GGUFMetadataValue(value_type, value)
    
    def _read_tensor_info(self, f):
        """Read tensor information"""
        name = self._read_string(f)
        n_dims = struct.unpack('<I', f.read(4))[0]
        dims = [struct.unpack('<Q', f.read(8))[0] for _ in range(n_dims)]
        tensor_type = struct.unpack('<I', f.read(4))[0]
        offset = struct.unpack('<Q', f.read(8))[0]
        
        tensor = GGUFTensor(name, dims, tensor_type, offset)
        self.tensors[name] = tensor
    
    def read_tensor_data(self, tensor: GGUFTensor) -> bytes:
        """Read tensor data from file"""
        with open(self.path, 'rb') as f:
            f.seek(self.tensor_data_offset + tensor.offset)
            return f.read(tensor.size)

def extract_layer_index(tensor_name: str) -> Optional[int]:
    """Extract layer index from tensor name (e.g., 'blk.5.ffn_gate.weight' -> 5)"""
    parts = tensor_name.split('.')
    for i, part in enumerate(parts):
        if part == 'blk' and i + 1 < len(parts):
            try:
                return int(parts[i + 1])
            except ValueError:
                pass
    return None

def is_layer_tensor(tensor_name: str) -> bool:
    """Check if tensor belongs to a specific layer"""
    return extract_layer_index(tensor_name) is not None

def merge_gguf_files(
    q4k_path: Path,
    pq20_path: Path,
    output_path: Path,
    ane_layers: Set[int]
):
    """
    Merge Q4_K_M and PQ2_0 GGUF files into hybrid GGUF.
    
    Args:
        q4k_path: Path to Q4_K_M GGUF file
        pq20_path: Path to PQ2_0 GGUF file
        output_path: Path to output hybrid GGUF file
        ane_layers: Set of layer indices to use Q4_K_M (ANE-compatible)
    """
    print(f"Loading Q4_K_M file: {q4k_path}")
    q4k_file = GGUFFile(q4k_path)
    
    print(f"Loading PQ2_0 file: {pq20_path}")
    pq20_file = GGUFFile(pq20_path)
    
    # Validate files have matching architecture
    if q4k_file.metadata.keys() != pq20_file.metadata.keys():
        print("Warning: Metadata keys differ between files")
    
    # Build hybrid tensor list
    hybrid_tensors: Dict[str, Tuple[GGUFFile, GGUFTensor]] = {}
    
    for name, tensor in pq20_file.tensors.items():
        layer_idx = extract_layer_index(name)
        
        if layer_idx is not None and layer_idx in ane_layers:
            # Use Q4_K_M for ANE layers
            if name in q4k_file.tensors:
                hybrid_tensors[name] = (q4k_file, q4k_file.tensors[name])
                print(f"  Layer {layer_idx}: {name} -> Q4_K_M (ANE)")
            else:
                print(f"Warning: Tensor {name} not found in Q4_K_M file, using PQ2_0")
                hybrid_tensors[name] = (pq20_file, tensor)
        else:
            # Use PQ2_0 for GPU layers and non-layer tensors
            hybrid_tensors[name] = (pq20_file, tensor)
            if layer_idx is not None:
                print(f"  Layer {layer_idx}: {name} -> PQ2_0 (GPU)")
    
    # Write hybrid GGUF file
    print(f"\nWriting hybrid GGUF: {output_path}")
    write_hybrid_gguf(output_path, pq20_file.metadata, hybrid_tensors)
    
    # Print statistics
    q4k_count = sum(1 for f, _ in hybrid_tensors.values() if f == q4k_file)
    pq20_count = len(hybrid_tensors) - q4k_count
    total_size = sum(tensor.size for _, tensor in hybrid_tensors.values())
    
    print(f"\nHybrid GGUF statistics:")
    print(f"  Total tensors: {len(hybrid_tensors)}")
    print(f"  Q4_K_M tensors: {q4k_count}")
    print(f"  PQ2_0 tensors: {pq20_count}")
    print(f"  Total size: {total_size / (1024**3):.2f} GB")
    print(f"  Output file: {output_path}")

def write_hybrid_gguf(
    output_path: Path,
    metadata: Dict[str, GGUFMetadataValue],
    tensors: Dict[str, Tuple[GGUFFile, GGUFTensor]]
):
    """Write hybrid GGUF file"""
    with open(output_path, 'wb') as f:
        # Write header
        f.write(struct.pack('<I', GGUF_MAGIC))
        f.write(struct.pack('<I', GGUF_VERSION))
        f.write(struct.pack('<Q', len(tensors)))
        f.write(struct.pack('<Q', len(metadata)))
        
        # Write metadata
        for key, value in metadata.items():
            _write_string(f, key)
            f.write(struct.pack('<I', value.value_type))
            _write_metadata_value(f, value)
        
        # Write tensor info
        current_offset = 0
        tensor_list = []
        for name, (source_file, tensor) in tensors.items():
            _write_string(f, name)
            f.write(struct.pack('<I', len(tensor.dims)))
            for dim in tensor.dims:
                f.write(struct.pack('<Q', dim))
            f.write(struct.pack('<I', tensor.tensor_type))
            f.write(struct.pack('<Q', current_offset))
            
            tensor_list.append((source_file, tensor, current_offset))
            current_offset += tensor.size
        
        # Align to GGUF_DEFAULT_ALIGNMENT
        tensor_data_offset = (f.tell() + GGUF_DEFAULT_ALIGNMENT - 1) & ~(GGUF_DEFAULT_ALIGNMENT - 1)
        f.write(b'\x00' * (tensor_data_offset - f.tell()))
        
        # Write tensor data
        for source_file, tensor, _ in tensor_list:
            data = source_file.read_tensor_data(tensor)
            f.write(data)

def _write_string(f, s: str):
    """Write length-prefixed string"""
    encoded = s.encode('utf-8')
    f.write(struct.pack('<Q', len(encoded)))
    f.write(encoded)

def _write_metadata_value(f, value: GGUFMetadataValue):
    """Write metadata value"""
    formats = {
        0: '<B', 1: '<b', 2: '<H', 3: '<h',
        4: '<I', 5: '<i', 6: '<f', 7: '<?',
        10: '<Q', 11: '<q', 12: '<d'
    }
    
    if value.value_type == 8:  # STRING
        _write_string(f, value.value)
    elif value.value_type in formats:
        f.write(struct.pack(formats[value.value_type], value.value))
    elif value.value_type == 9:  # ARRAY
        # Write empty array for simplicity
        f.write(struct.pack('<I', 0))  # array type
        f.write(struct.pack('<Q', 0))  # array length

